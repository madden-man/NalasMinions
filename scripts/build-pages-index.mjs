// Builds public/pages.html, the /pages index of every public page, from the
// PAGES registry in src/links.js: one card per page with its blurb and a jump
// link to each section. Generated so a newly registered page appears without
// editing the index; test/pages.test.mjs fails if the committed file is stale.
// Run `npm run build:pages` after changing PAGES and commit both.

import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { PAGES, pagePath } from '../src/links.js'

export const INDEX_FILE = 'public/pages.html'

const esc = (s) =>
  String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c])

function card(p) {
  const href = pagePath(p)
  const sections = p.sections
    .map((s) => `<li><a href="${href}#${esc(s.id)}">${esc(s.label)}</a></li>`)
    .join('')
  return `<article class="card" id="page-${esc(p.key)}">
  <h2><a href="${href}">${esc(p.name)}</a></h2>
  <p class="url">nalasminions.netlify.app${href}</p>
  <p>${esc(p.blurb ?? '')}</p>
  <details><summary>${p.sections.length} sections</summary><ul>${sections}</ul></details>
</article>`
}

export function renderIndex(pages = PAGES) {
  return `<!DOCTYPE html>
<!-- Generated by scripts/build-pages-index.mjs from PAGES in src/links.js. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
<meta name="robots" content="noindex">
<title>Nala's Minions pages</title>
<link rel="icon" href="/favicon-32.png">
<style>
:root { --bg: #f4f2ec; --card: #fffdf8; --ink: #1d1f1b; --muted: #62665e; --line: #dcd8cc; --accent: #6b3fa0; }
@media (prefers-color-scheme: dark) { :root { --bg: #131412; --card: #1c1d1a; --ink: #ecebe5; --muted: #a3a59c; --line: #33352f; --accent: #c3a2ff; color-scheme: dark; } }
* { box-sizing: border-box; }
body { margin: 0; background: var(--bg); color: var(--ink); font: 16px/1.5 system-ui, -apple-system, "Segoe UI", sans-serif; }
.wrap { max-width: 920px; margin: 0 auto; padding: 32px max(16px, env(safe-area-inset-left, 0px)) 64px; }
header { display: flex; flex-wrap: wrap; align-items: baseline; justify-content: space-between; gap: 8px 24px; margin-bottom: 24px; }
h1 { margin: 0; font-size: clamp(28px, 6vw, 40px); letter-spacing: -.01em; }
header a { color: var(--accent); font-weight: 600; text-decoration: none; }
.grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(260px, 1fr)); gap: 16px; }
.card { background: var(--card); border: 1px solid var(--line); border-radius: 12px; padding: 18px 18px 14px; display: grid; gap: 6px; align-content: start; }
.card h2 { margin: 0; font-size: 20px; }
.card h2 a { color: var(--ink); text-decoration: none; }
.card h2 a:hover { color: var(--accent); }
.card p { margin: 0; color: var(--muted); }
.card .url { font: 12px ui-monospace, Menlo, monospace; color: var(--accent); }
details { margin-top: 6px; font-size: 14px; }
summary { cursor: pointer; color: var(--muted); }
ul { margin: 8px 0 0; padding-left: 18px; columns: 2; column-gap: 16px; }
li { break-inside: avoid; }
li a { color: var(--ink); }
</style>
</head>
<body>
<main class="wrap">
<header><h1>Nala's Minions pages</h1><a href="/">Open the chores app →</a></header>
<div class="grid">
${pages.map(card).join('\n')}
</div>
</main>
</body>
</html>
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
  writeFileSync(path.join(root, INDEX_FILE), renderIndex())
  console.log(`wrote ${INDEX_FILE} (${PAGES.length} pages)`)
}
